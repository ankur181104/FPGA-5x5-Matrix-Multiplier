`timescale 1ns / 1ps

module tb_matrix_element_5x5;

    reg  [3:0] A0,A1,A2,A3,A4;
    reg  [3:0] W0,W1,W2,W3,W4;
    wire [16:0] Y;

    matrix_element_5x5 DUT (
        A0,A1,A2,A3,A4,
        W0,W1,W2,W3,W4,
        Y
    );

    initial begin
        // A = [0,0,0,0,0]  W = [0,0,0,0,0]   Expected Y = 00000 hex
        A0=4'd0; A1=4'd0; A2=4'd0; A3=4'd0; A4=4'd0;
        W0=4'd0; W1=4'd0; W2=4'd0; W3=4'd0; W4=4'd0;
        #10;

        // A = [4,0,0,0,0]  W = [5,0,0,0,0]   Expected Y = 5*4 = 20 = 00014 hex
        A0=4'd4; A1=4'd0; A2=4'd0; A3=4'd0; A4=4'd0;
        W0=4'd5; W1=4'd0; W2=4'd0; W3=4'd0; W4=4'd0;
        #10;

        // A = [1,1,1,1,1]  W = [1,1,1,1,1]   Expected Y = 1+1+1+1+1 = 5 = 00005 hex
        A0=4'd1; A1=4'd1; A2=4'd1; A3=4'd1; A4=4'd1;
        W0=4'd1; W1=4'd1; W2=4'd1; W3=4'd1; W4=4'd1;
        #10;

        // A = [2,3,4,5,6]  W = [1,2,3,4,5]   Expected Y = 1*2 + 3*2 + 3*4 + 5*4 + 6*5 = 70 = 00046 hex
        A0=4'd2; A1=4'd3; A2=4'd4; A3=4'd5; A4=4'd6;
        W0=4'd1; W1=4'd2; W2=4'd3; W3=4'd4; W4=4'd5;
        #10;

        // A = [15,15,15,15,15]  W = [15,15,15,15,15]   Expected Y = 15*15 + 15*15 + 15*15 + 15*15 + 15*15 = 1125 = 00465 hex
        A0=4'd15; A1=4'd15; A2=4'd15; A3=4'd15; A4=4'd15;
        W0=4'd15; W1=4'd15; W2=4'd15; W3=4'd15; W4=4'd15;
        #10;

        // A = [7,3,12,1,9]  W = [4,6,2,8,5]   Expected Y = 7*4 + 3*6 + 12*2 + 1*8 + 9*5 = 123 = 0007B hex
        A0=4'd7; A1=4'd3; A2=4'd12; A3=4'd1; A4=4'd9;
        W0=4'd4; W1=4'd6; W2=4'd2; W3=4'd8; W4=4'd5;
        #10;

        $stop;
    end

endmodule
