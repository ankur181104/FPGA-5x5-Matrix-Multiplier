`timescale 1ns / 1ps

module matrix_element_5x5 (
    input  [3:0] A0, A1, A2, A3, A4,
    input  [3:0] W0, W1, W2, W3, W4,
    output [15:0] Y
);

    wire [7:0] P0, P1, P2, P3, P4;
    wire [15:0] S0,S1,S2;
    wire C0,C1,C2;

   
    multiplier M0(
    A0[0],A0[1],A0[2],A0[3], 
    W0[0],W0[1],W0[2],W0[3], 
    
    P0[0],P0[1],P0[2],P0[3],P0[4],P0[5],P0[6],P0[7]
    );
    
    multiplier M1(
    A1[0],A1[1],A1[2],A1[3], 
    W1[0],W1[1],W1[2],W1[3], 
    
    P1[0],P1[1],P1[2],P1[3],P1[4],P1[5],P1[6],P1[7]
    );
    
    multiplier M2(
    A2[0],A2[1],A2[2],A2[3], 
    W2[0],W2[1],W2[2],W2[3], 
    
    P2[0],P2[1],P2[2],P2[3],P2[4],P2[5],P2[6],P2[7]
    );
    
    multiplier M3(
    A3[0],A3[1],A3[2],A3[3], 
    W3[0],W3[1],W3[2],W3[3], 
    
    P3[0],P3[1],P3[2],P3[3],P3[4],P3[5],P3[6],P3[7]
    );
    
    multiplier M4(
    A4[0],A4[1],A4[2],A4[3], 
    W4[0],W4[1],W4[2],W4[3], 
    
    P4[0],P4[1],P4[2],P4[3],P4[4],P4[5],P4[6],P4[7]
    );
    
    
    //S0 = P0 + P1
    sixteen_bit_adder SBA1(
    P0[0],P0[1],P0[2],P0[3],P0[4],P0[5],P0[6],P0[7], // A [7:0]
    1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,         // A [15:8]
    
    P1[0],P1[1],P1[2],P1[3],P1[4],P1[5],P1[6],P1[7], // B [7:0]
    1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,         // B [15:8]
    1'b0, // cin
    
    
    S0[0],S0[1],S0[2],S0[3],S0[4],S0[5],S0[6],S0[7],S0[8],S0[9],S0[10],S0[11],S0[12],S0[13],S0[14],S0[15], // o/p [15:0]
        C0  // cout
        
    );
    
    //S1 = S0 + P2
    sixteen_bit_adder SBA2(
    
    S0[0],S0[1],S0[2],S0[3],S0[4],S0[5],S0[6],S0[7],             // A [7:0]
    S0[8],S0[9],S0[10],S0[11],S0[12],S0[13],S0[14],S0[15],       // A [15:8]
    
    P2[0],P2[1],P2[2],P2[3],P2[4],P2[5],P2[6],P2[7], // B [7:0]
    1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,         // B [15:8]
    C0, // cin
    
    S1[0],S1[1],S1[2],S1[3],S1[4],S1[5],S1[6],S1[7],S1[8],S1[9],S1[10],S1[11],S1[12],S1[13],S1[14],S1[15], // o/p [15:0]
    C1  // cout
    );
    
    //S2 = S1 + P3
    sixteen_bit_adder SBA3(
    
    S1[0],S1[1],S1[2],S1[3],S1[4],S1[5],S1[6],S1[7],              // A [7:0]
    S1[8],S1[9],S1[10],S1[11],S1[12],S1[13],S1[14],S1[15],        // A [15:8]
    
    P3[0],P3[1],P3[2],P3[3],P3[4],P3[5],P3[6],P3[7], // B [7:0]
    1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,         // B [15:8]
    C1, // cin
    
    S2[0],S2[1],S2[2],S2[3],S2[4],S2[5],S2[6],S2[7],S2[8],S2[9],S2[10],S2[11],S2[12],S2[13],S2[14],S2[15], // o/p [15:0]
    C2  // cout
    );
    
    //Y = S2 + P4
    sixteen_bit_adder SBA4(
    
    S2[0],S2[1],S2[2],S2[3],S2[4],S2[5],S2[6],S2[7],              // A [7:0]
    S2[8],S2[9],S2[10],S2[11],S2[12],S2[13],S2[14],S2[15],        // A [15:8]
    
    P4[0],P4[1],P4[2],P4[3],P4[4],P4[5],P4[6],P4[7], // B [7:0]
    1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,1'b0,         // B [15:8]
    C2, // cin
    
    Y[0],Y[1],Y[2],Y[3],Y[4],Y[5],Y[6],Y[7],Y[8],Y[9],Y[10],Y[11],Y[12],Y[13],Y[14],Y[15], // o/p [15:0]
    Y[16]  // cout
    );
    

endmodule
